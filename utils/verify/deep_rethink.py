"""深度重解（deep_rethink）的可复用件：换方法引导语 + 温度。

深度重解与 self-consistency 多采样的根本区别：多采样靠「高温 + 重复采样」取多数票，
但 intern-s2 非 Preview 在 0.7 温度下采样无多样性（答案与首轮高度一致、零覆盖），
已被证伪。深度重解不靠采样多样性——它低温（0.3，与首轮一致）单次重算，靠
「定向引导模型换一种方法/视角 + 主动检查易漏点（孤立解/边界/最坏情形）」来发现
首轮的漏解/建模错。

入口在 graph/nodes/reasoning.py 的 `_maybe_deep_rethink_override`（深度重解**前置**，
挂 reasoning 首轮成功路径）：首轮成功后软预算还剩 ~670s，深度重解发得出；覆盖逻辑
「换方法答案与首轮不同且非退化才覆盖」，否则静默保留首轮。此前尝试过 invoke 后置
（low 置信信号驱动），但 invoke 后 remaining_hard 不足单次完整 CoT + 余量，发不出
（与 consistency_vote 根因 1 相同），故改为前置。
"""

from __future__ import annotations

from config import CONFIG

#: 深度重解引导语：换方法 + 检查易漏点（漏解/边界/最坏情形）。深度重解注入首轮
#: 答案做「反思式」重解（多采样的独立性假设在这里不成立也不需要——我们要的是
#: 「针对首轮的纠错」，不是「独立的重复」）。
_DEEP_RETHINK_GUIDE = (
    "\n\n[换方法深度复核] 请换一种与之前完全不同的方法/视角重新求解本题"
    "（例如：之前用代数就用几何/枚举/对称性；之前正向推导就尝试反向验证或构造反例）。"
    "求解过程中主动检查以下易漏点：\n"
    "  1. 孤立解/边界解/退化情形——把最小的几个值（如 v=0,1,2,3）逐个代入原条件显式检验；\n"
    "  2. 「所有解」是否找全——不要只给通解族而漏掉不属任何族的孤立解；\n"
    "  3. 题面含 regardless of / guarantee / 不管 / 保证 时，是否按「对手最坏情形」理解。\n"
    "最后必须给出 '## 最终答案'。若复核发现此前答案有漏或有错，直接给出纠正后的正确答案；"
    "若此前答案正确，原样重述该答案即可。"
)


def _deep_temperature() -> float:
    """深度重解温度：与首轮一致（0.3），不抬——靠换方法引导而非采样噪声。"""
    return float(CONFIG["temperatures"].get("reasoning", 0.3))
